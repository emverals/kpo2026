"""Скриптованная демонстрация: ConsoleApp прогоняется по заготовленному вводу.

Используется тот же контейнер и то же меню, что и в интерактивном режиме, —
демонстрируется ровно то, что увидит пользователь.
"""

from vyshcat.console.io import ConsoleIO, ScriptedIO

DEMO_STEPS: tuple[tuple[str, list[str]], ...] = (
    ("Пустой парк: отчёт, новички и опись до приёма техники", ["3", "4", "5"]),
    (
        "Приём электросамоката (простой и экономичный, годится новичкам)",
        ["1", "1", "Ninebot Max G30", "8", "0.6", ""],
    ),
    ("Приём велосипеда (энергию не потребляет)", ["1", "2", "Stels Navigator", "9", ""]),
    (
        "Приём электровелосипеда (простой, но расход > 1 кВт·ч — не для новичков)",
        ["1", "3", "Eltreco XT 800", "7", "1.2", ""],
    ),
    ("Отклонение: заявлены неисправности", ["1", "1", "Kugoo S3", "7", "0.5", "тормоз, люфт руля"]),
    ("Отклонение: аномальный расход энергии", ["1", "3", "Монстр 3000", "5", "9.5", ""]),
    (
        "Некорректный ввод: мусор вместо чисел и пустое имя",
        ["7", "1", "abc", "1", "", "Xiaomi 4 Pro", "11", "7", "-1", "0,45", ""],
    ),
    ("Вещь без энергии: шлем (без техосмотра)", ["2", "1", "Шлем детский S"]),
    ("Вещь-потребитель: док-станция", ["2", "2", "Док у корпуса Покровка", "1.5"]),
    ("Вещь-потребитель: зарядный шкаф", ["2", "3", "Шкаф на Мясницкой", "3"]),
    ("Отчёт: количество и суммарная суточная энергия", ["3"]),
    ("Транспорт для новичков", ["4"]),
    ("Инвентарная опись техники и вещей", ["5"]),
    ("Выход", ["0"]),
)


def build_demo_io(output: ConsoleIO | None = None) -> ScriptedIO:
    out = output or ConsoleIO()
    answers: list[str] = []
    headings: dict[int, str] = {}
    for title, step in DEMO_STEPS:
        headings[len(answers)] = f"\n########## ДЕМО: {title} ##########"
        answers.extend(step)
    return ScriptedIO(write=out.write, answers=answers, headings=headings)
